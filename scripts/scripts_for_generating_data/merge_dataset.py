def should_skip_step(step):
    """Return True when the current step is the initial timestep."""
    return step.get('step_idx') == 0


# help function
def load_json(path, verbose=False):
    if verbose:
        print(f"Loading: {path}")
    if not os.path.exists(path):
        return None
    with open(path, 'r') as f:
        try:
            return json.load(f)
        except json.JSONDecodeError as exc:
            err_msg = (
                f"BAD JSON FILE: {path} (line {exc.lineno}, column {exc.colno}): {exc.msg}"
            )
            print(err_msg)
            raise ValueError(err_msg) from exc


def safe_write_json(path, data, indent=4):
    """Atomically write JSON with per-file lock and post-write validation.

    This prevents partially-written/corrupted JSON when processes overlap
    or when execution is interrupted during write.
    """
    dir_path = os.path.dirname(path) or "."
    os.makedirs(dir_path, exist_ok=True)
    lock_path = f"{path}.lock"

    with open(lock_path, 'w') as lock_f:
        fcntl.flock(lock_f.fileno(), fcntl.LOCK_EX)
        fd, tmp_path = tempfile.mkstemp(
            prefix=f".{os.path.basename(path)}.",
            suffix=".tmp",
            dir=dir_path,
            text=True,
        )
        try:
            with os.fdopen(fd, 'w') as tmp_f:
                json.dump(data, tmp_f, indent=indent)
                tmp_f.flush()
                os.fsync(tmp_f.fileno())

            # Verify temp file contains valid JSON before replace.
            with open(tmp_path, 'r') as vf:
                json.load(vf)

            os.replace(tmp_path, path)

            # Best-effort directory fsync for durability.
            try:
                dir_fd = os.open(dir_path, os.O_RDONLY)
                try:
                    os.fsync(dir_fd)
                finally:
                    os.close(dir_fd)
            except OSError:
                pass
        except Exception:
            if os.path.exists(tmp_path):
                os.remove(tmp_path)
            raise
        finally:
            fcntl.flock(lock_f.fileno(), fcntl.LOCK_UN)

# step 1: merge pixel data into trajectory data
def merge_pixel_data(verbose=False):
    print(f"Merging pixel from {DATA_DIR}...")
    print(f"Base: {train_trajectory_path}")
    print(f"Output: {output_path}")

    traj_annot_dir = os.path.join(train_trajectory_path, "adjusted_annotations")
    if not os.path.exists(traj_annot_dir):
        print(f"Error: Trajectory annotation directory not found: {traj_annot_dir}")
        return

    os.makedirs(output_path, exist_ok=True)

    for root, dirs, files in os.walk(traj_annot_dir):
        for file in tqdm(files, desc="Merging pixel"):
            if not file.endswith(".json"):
                continue

            scene_id = os.path.basename(root)
            ep_id = file

            traj_file = os.path.join(root, file)
            pixel_file = os.path.join(train_pixel_path, "adjusted_annotations", scene_id, ep_id)

            scene_output_dir = os.path.join(output_path, scene_id)
            os.makedirs(scene_output_dir, exist_ok=True)
            merged_output_file = os.path.join(scene_output_dir, ep_id)

            # Load trajectory
            traj_data = load_json(traj_file, verbose=verbose)
            if traj_data is None:
                continue

            # Optionally load and validate pixel
            pixel_data = None
            pixel_step_lookup = {}
            if IF_PIXEL_MERGE:
                pixel_data = load_json(pixel_file, verbose=verbose)
                if pixel_data is None:
                    continue

                steps = pixel_data['steps']
                pixel_valid = True
                for i, step in enumerate(steps):
                    if step['step_idx'] == 0:
                        continue
                    if i == len(steps) - 1:
                        continue
                    # Check if at least one pixel attribute is present
                    has_pixel = any(attr in step for attr in pixel_attributes)
                    if not has_pixel:
                        print(f"Warning: No pixel attributes found in step {step['step_idx']} of {ep_id}")
                        pixel_valid = False
                        break
                if not pixel_valid:
                    if verbose:
                        print(f"Skipping {ep_id}: Missing pixel attributes")
                    continue

                pixel_step_lookup = {
                    step['step_idx']: step
                    for step in pixel_data.get('steps', [])
                    if 'step_idx' in step
                }

            # Merge pixel into trajectory base and overwrite original file
            for step in traj_data['steps']:
                if should_skip_step(step):
                    continue
                step_idx = step.get('step_idx')
                if not IF_PIXEL_MERGE or step_idx is None:
                    continue

                pixel_step = pixel_step_lookup.get(step_idx)
                if not pixel_step:
                    continue

                for key in pixel_attributes:
                    if key in pixel_step:
                        step[key] = pixel_step[key]

            safe_write_json(merged_output_file, traj_data, indent=4)

    print("Trajectory + pixel merge completed.")

# step 2: merge history data into merged data
def merge_history_into_annotations(verbose=False):
    print(f"Merging history into existing annotations from {train_history_path}")

    # We expect traj+pixel merged files to be present in output_path
    if not os.path.exists(output_path):
        print(f"Error: Output annotation directory not found: {output_path}")
        return

    for root, dirs, files in os.walk(output_path):
        for file in tqdm(files, desc="Merging history"):
            if not file.endswith(".json"):
                continue

            scene_id = os.path.basename(root)
            ep_id = file

            merged_file = os.path.join(root, file)
            history_file = os.path.join(train_history_path, "annotations", scene_id, ep_id)

            merged_data = load_json(merged_file, verbose=verbose)
            if merged_data is None:
                continue

            if not IF_HISTORY_MERGE:
                # Nothing to do; keep as-is
                continue

            # If corresponding history annotation does not exist, delete this merged json file
            if not os.path.exists(history_file):
                try:
                    os.remove(merged_file)
                    if verbose:
                        print(f"Deleted orphan annotation (no history): {scene_id}/{ep_id}")
                except OSError as e:
                    print(f"Failed to delete {merged_file}: {e}")
                continue

            history_data = load_json(history_file, verbose=verbose)
            if history_data is None:
                # No history available; delete merged file per new rule
                try:
                    os.remove(merged_file)
                    if verbose:
                        print(f"Deleted orphan annotation (bad history json): {scene_id}/{ep_id}")
                except OSError as e:
                    print(f"Failed to delete {merged_file}: {e}")
                continue

            # Validate: proceed if any of the history attributes appears in any step
            steps = history_data['steps']
            has_any_history_attr = False
            for s in steps:
                for attr in history_attributes:
                    if attr in s:
                        has_any_history_attr = True
                        break
                if has_any_history_attr:
                    break

            if not has_any_history_attr:
                if verbose:
                    print(f"Skipping {ep_id}: No history attributes found")
                continue

            # Merge history into existing merged data
            changed = False
            vis_list_keys = ['his_tra_multip_colored', 'his_tra_single_colored', 'his_tra_without_colored']
            for i, step in enumerate(merged_data['steps']):
                if should_skip_step(step):
                    continue
                if history_data and i < len(history_data['steps']):
                    history_step = history_data['steps'][i]
                    for key in history_attributes:
                        if key in history_step:
                            if key in vis_list_keys and isinstance(history_step[key], list):
                                step[key] = history_step[key][::-1]
                            else:
                                step[key] = history_step[key]
                            changed = True

            if changed:
                safe_write_json(merged_file, merged_data, indent=4)

    print("History merge completed.")

def generated_history_image_with_interval(intervals=[1], numbers=[8]):
    """Generate interval-based history image paths.

    Args:
        intervals: List of sampling intervals.
        numbers: Number of images to sample for each interval.
            If None, defaults to 5 images for every interval.
            Example: intervals=[1, 2], numbers=[2, 3]
            means sample 2 images with interval 1, and 3 images with interval 2.
    """
    if numbers is None:
        numbers = [5] * len(intervals)

    if len(intervals) != len(numbers):
        raise ValueError(
            f"intervals and numbers must have the same length, got {len(intervals)} and {len(numbers)}"
        )

    if any(n <= 0 for n in numbers):
        raise ValueError(f"All values in numbers must be positive, got {numbers}")

    print(f"Generating history images with intervals {intervals} and counts {numbers}...")
    
    if not os.path.exists(output_path):
        print(f"Error: Output annotation directory not found: {output_path}")
        return

    for root, dirs, files in os.walk(output_path):
        for file in tqdm(files, desc="Processing history intervals"):
            if not file.endswith(".json"):
                continue
            
            merged_file = os.path.join(root, file)
            merged_data = load_json(merged_file)
            if merged_data is None:
                continue
            
            steps = merged_data['steps']
            
            for i, step in enumerate(steps):
                if should_skip_step(step):
                    continue
                step_idx = step['step_idx']
                
                for interval, num_images in zip(intervals, numbers):
                    history_paths = []
                    # Generate indices: step_idx - interval, step_idx - 2*interval, ...
                    # Number of frames is controlled by num_images for each interval.
                    for k in range(1, num_images + 1):
                        target_idx = step_idx - k * interval
                        if target_idx >= 0 and target_idx < len(steps):
                            # Find the step with this index (usually steps[target_idx] if sorted, but let's be safe)
                            # Assuming steps are sorted by step_idx and contiguous
                            target_step = steps[target_idx]
                            if target_step['step_idx'] == target_idx:
                                if 'rgb_path' in target_step:
                                    history_paths.append(target_step['rgb_path'])
                            else:
                                # Fallback search if not contiguous/sorted
                                for s in steps:
                                    if s['step_idx'] == target_idx:
                                        if 'rgb_path' in s:
                                            history_paths.append(s['rgb_path'])
                                        break
                    
                    step[f'history_vis_interval_{interval}'] = history_paths
            
            safe_write_json(merged_file, merged_data, indent=4)

    print("History interval generation completed.")

def generated_history_image_with_uniform_sampling(num_images=8, verbose=False):
    print(f"Generating history images with uniform sampling (num_images={num_images})...")
    
    if not os.path.exists(output_path):
        print(f"Error: Output annotation directory not found: {output_path}")
        return

    for root, dirs, files in os.walk(output_path):
        for file in tqdm(files, desc="Processing uniform sampling"):
            if not file.endswith(".json"):
                continue
            
            merged_file = os.path.join(root, file)
            merged_data = load_json(merged_file)
            if merged_data is None:
                continue
            
            steps = merged_data['steps']
            
            for i, step in enumerate(steps):
                if should_skip_step(step):
                    continue
                step_idx = step['step_idx']
                history_paths = []

                # Only sample from valid history steps that have rgb_path.
                valid_history_indices = [
                    s['step_idx']
                    for s in steps
                    if s.get('step_idx', -1) < step_idx and 'rgb_path' in s
                ]
                
                if len(valid_history_indices) < num_images:
                    # Not enough history: keep the first n available history frames.
                    indices = list(valid_history_indices)
                else:
                    # Uniformly sample num_images indices from valid history pool.
                    picked_pos = [int(k * len(valid_history_indices) / num_images) for k in range(num_images)]
                    indices = [valid_history_indices[p] for p in picked_pos]
                
                # Reverse indices to be Recent -> Old
                indices = indices[::-1]

                for target_idx in indices:
                    if target_idx >= 0 and target_idx < len(steps):
                        # Assuming steps are sorted by step_idx and contiguous
                        target_step = steps[target_idx]
                        if target_step['step_idx'] == target_idx:
                            if 'rgb_path' in target_step:
                                history_paths.append(target_step['rgb_path'])
                        else:
                            # Fallback search
                            for s in steps:
                                if s['step_idx'] == target_idx:
                                    if 'rgb_path' in s:
                                        history_paths.append(s['rgb_path'])
                                    break

                    if verbose and len(history_paths) < num_images and len(valid_history_indices) >= num_images:
                        print(
                            f"[uniform_sampling] {merged_file} step_idx={step_idx} "
                            f"generated {len(history_paths)}<{num_images} history images"
                        )
                
                step['history_vis_uniform_sampling'] = history_paths
            
            safe_write_json(merged_file, merged_data, indent=4)

    print("Uniform sampling generation completed.")

def generated_history_image_with_sampling_with_diff_frequency(first_window=20, first_num=4, second_num=4, verbose=False):
    target_total = first_num + second_num
    print(
        "Generating history images with diff frequency sampling "
        f"(first_window={first_window}, first_num={first_num}, second_num={second_num}, total={target_total})..."
    )
    
    if not os.path.exists(output_path):
        print(f"Error: Output annotation directory not found: {output_path}")
        return

    for root, dirs, files in os.walk(output_path):
        for file in tqdm(files, desc="Processing diff frequency sampling"):
            if not file.endswith(".json"):
                continue
            
            merged_file = os.path.join(root, file)
            if verbose:
                print(f"[diff_frequency] processing file: {merged_file}")
            merged_data = load_json(merged_file)
            if merged_data is None:
                continue
            
            steps = merged_data['steps']
            
            for i, step in enumerate(steps):
                if should_skip_step(step):
                    continue
                step_idx = step['step_idx']
                history_paths = []
                
                # Available history indices: only use valid steps with rgb_path.
                available_indices = [
                    s['step_idx']
                    for s in steps
                    if s.get('step_idx', -1) < step_idx and 'rgb_path' in s
                ]
                
                def uniform_pick(indices, k):
                    if k <= 0:
                        return []
                    if len(indices) <= k:
                        return list(indices)
                    picked_pos = [int(i * len(indices) / k) for i in range(k)]
                    return [indices[p] for p in picked_pos]

                first_part_indices = available_indices[:first_window]
                second_part_indices = available_indices[first_window:]

                selected_first = uniform_pick(first_part_indices, first_num)
                selected_second = uniform_pick(second_part_indices, second_num)
                selected_indices = selected_first + selected_second

                # If one side has insufficient images, fill remaining slots from all unselected history.
                if len(selected_indices) < target_total:
                    selected_set = set(selected_indices)
                    remaining_pool = [idx for idx in available_indices if idx not in selected_set]
                    remaining_needed = target_total - len(selected_indices)
                    selected_indices.extend(uniform_pick(remaining_pool, remaining_needed))

                # Reverse selected_indices to be Recent -> Old
                selected_indices = selected_indices[::-1]

                # Retrieve paths
                for target_idx in selected_indices:
                    # Find step with this index
                    # Assuming sorted and contiguous for efficiency, but fallback to search
                    if target_idx < len(steps) and steps[target_idx]['step_idx'] == target_idx:
                         if 'rgb_path' in steps[target_idx]:
                            history_paths.append(steps[target_idx]['rgb_path'])
                    else:
                        for s in steps:
                            if s['step_idx'] == target_idx:
                                if 'rgb_path' in s:
                                    history_paths.append(s['rgb_path'])
                                break

                if verbose and len(history_paths) < target_total and len(available_indices) >= target_total:
                    print(
                        f"[diff_frequency] {merged_file} step_idx={step_idx} "
                        f"generated {len(history_paths)}<{target_total} history images"
                    )
                
                step['history_vis_diff_frequency'] = history_paths
            
            try:
                safe_write_json(merged_file, merged_data, indent=4)
            except Exception as exc:
                raise RuntimeError(f"Failed while writing processed file: {merged_file}") from exc

    print("Diff frequency sampling generation completed.")



